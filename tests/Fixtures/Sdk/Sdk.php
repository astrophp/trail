<?php

namespace Astro\Trail\Tests\Fixtures\Sdk;

use Composer\InstalledVersions;
use RuntimeException;

/**
 * What the installed laravel/ai does where its releases differ, each named for the behaviour and
 * read from the version Composer installed. tests/Feature/Sdk/SdkBehaviourFlagsTest.php checks
 * every flag against what the SDK actually does.
 */
final class Sdk
{
    /**
     * A tool that throws fires ToolFailed, the SDK reports the exception, answers the model with
     * "The tool call failed: ..." and asks for another step. Before 1.4.0 the exception ends the run.
     */
    public static function recoversFromToolFailures(): bool
    {
        return self::atLeast('1.4.0');
    }

    /**
     * A sub-agent that throws fails the agent tool that delegated to it, with the sub-agent's
     * exception. Before 1.4.1 the agent tool returns "Agent failed: ..." as an ordinary result.
     */
    public static function failsAgentToolWithSubAgent(): bool
    {
        return self::atLeast('1.4.1');
    }

    /**
     * The title of a new conversation is generated by an agent run of its own, under the run that
     * opened the conversation, with its own agent events. Before 1.4.0 the call fires no event.
     */
    public static function reportsTitleCallAsAgentRun(): bool
    {
        return self::atLeast('1.4.0');
    }

    /**
     * A 401 raises InvalidApiKeyException. Before 1.4.1 it is the HTTP client's RequestException.
     */
    public static function raisesInvalidApiKey(): bool
    {
        return self::atLeast('1.4.1');
    }

    /**
     * The installed laravel/ai version, as major.minor.patch.
     */
    public static function version(): string
    {
        if (! InstalledVersions::isInstalled('laravel/ai')) {
            throw new RuntimeException('laravel/ai is not installed.');
        }

        $version = (string) InstalledVersions::getVersion('laravel/ai');

        if (preg_match('/^(\d+\.\d+\.\d+)/', $version, $match) !== 1) {
            throw new RuntimeException("The installed laravel/ai version [{$version}] is not a release; the SDK's behaviour cannot be told from it.");
        }

        return $match[1];
    }

    private static function atLeast(string $version): bool
    {
        return version_compare(self::version(), $version, '>=');
    }
}
